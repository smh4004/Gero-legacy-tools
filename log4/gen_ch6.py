"""Chapter 6 'Taken' (Act 2, world 16 = West City at night, moonlit BG palette): the walk home through a city full of
Gero's machines. 16:1 West City at night (BF 4:1 map) -> south road -> 16:41 Riverside (BF 2:9) -> 16:42 Docks (BF 2:8)
-> barn door -> 16:43 Old Warehouse (the twins' hideout, the 4:43 map): the Collector (enemy row 76, BF Metal Hulk)
waits inside; its death loads 16:44 (same map) where the three drones close in (ch6_ambush) -> the lab.
Flags: 333 home intro, 334 Collector destroyed, 335 riverside cache, 336 docks cache, 337 crossroads scene; 305 ambush
done (existing). usage: python3 log4/gen_ch6.py (needs a built log4/out/LoG4.gba with 4:43)"""
import json, os
import areagen as G
from areagen import hexcond

W16 = 16
SRC = {1: ('bf', [4, 1]), 41: ('bf', [2, 9]), 42: ('bf', [2, 8]), 43: ('l2', None), 44: ('l2', None)}
SIZE = {1: (1072, 912), 41: (480, 320), 42: (480, 480), 43: (368, 301), 44: (368, 301)}
NAMES = {1: 'West City (night)', 41: 'Riverside (night)', 42: 'Docks (night)', 43: 'Old Warehouse (night)',
         44: 'Old Warehouse (ambush)'}
UI_NAME = {41: 1702, 42: 1703, 43: 1704, 44: 1704}
g = G.Gen(SRC, SIZE, world=W16)
g._m[43] = g._m[44] = G.OUT.walk_mask(G.OUT.map_of(4, 43))      # the chapter 5 warehouse map (LoG2 2:50)
g.link(1, ('down', 368, 472), 41, ('up', 224, 288), NAMES)
g.link(41, ('right', 176, 272), 42, ('down', 232, 280), NAMES)   # the docks' pier (was the west edge behind the trees)
S = lambda a, x, y, r=12, f=None: g.snap(a, x, y, r, f)
g.doors[42].append({'rect': [120, 186, 168, 208], 'warp': [W16, 43] + S(43, 140, 104, 14, 'down'), 'dir': 'up',
                    'face': 'down', '_note': 'Docks -> Old Warehouse (barn door)'})
g.doors[43].append({'rect': [120, 64, 192, 92], 'warp': [W16, 42] + S(42, 136, 214, 14, 'down'), 'dir': 'up',
                    'face': 'down', 'cover_ok': True, '_note': 'Old Warehouse -> Docks'})

home = S(43, 140, 104)
g.ev(43, (home[0] - 24, home[1] + 8, home[0] + 56, home[1] + 40), 'ch6_home', walk=True,
     when=hexcond(('clear', 333)), note='home at last: the Collector (333)')
AMB = S(44, 150, 176)                     # the boss's death script loads 16:44 here (stats.json row 76)
g.ev(44, (AMB[0] - 24, AMB[1] - 24, AMB[0] + 40, AMB[1] + 40), 'ch6_ambush', walk=True,
     when=hexcond(('clear', 305)), note='the drones close in (305)')
g.ev(1, (392, 336, 456, 470), 'night_crossroads', walk=True, when=hexcond(('clear', 337)),
     note='a drone sweeps the crossroads (337)')
g.ev(41, (40, 120, 72, 152), 'night_cache_river', examine='left', note='the rowboat (335)')
g.ev(42, (256, 186, 288, 240), 'night_cache_docks', note='the dome house (336). Rect reaches y 240: the player stops at y 232 in front of the door (2026-11-04 playthrough: the old rect ended at 208, out of reach)')

spawns = {44: [dict(x=150, y=104, actor='drone_night_a', face='down', no_check=True, _note='ambush drone A (moves in)'),
               dict(x=300, y=176, actor='drone_night_b', face='left', no_check=True, _note='ambush drone B'),
               dict(x=60, y=176, actor='drone_night_c', face='right', no_check=True, _note='ambush drone C')]}
E = lambda a, t, x, y, **k: dict(type=t, x=S(a, x, y, 14)[0], y=S(a, x, y, 14)[1], **k)
DRONE, COLLECTOR = 94, 76        # rows: Power Mechandoid (character 230), Metal Hulk (character 191)
enemies = {
    41: [E(41, DRONE, 200, 170), E(41, DRONE, 360, 220)],
    42: [E(42, DRONE, 100, 320), E(42, DRONE, 320, 260), E(42, DRONE, 230, 110)],
    43: [dict(E(43, COLLECTOR, 200, 220), character=191, condition=0x20000 + 334,
              _note='the Collector (row 76): until destroyed (334)')],
}
ents = []
for a in (41, 42, 43, 44):
    k, s = SRC[a]
    e = {'world': W16, 'area': a, 'template': [15, 10], 'name': UI_NAME[a], 'palette_act': 'act2', 'night': True,
         '_note': 'Chapter 6: %s (generated by log4/gen_ch6.py)' % NAMES[a], 'doors': g.doors[a],
         'map_from': s if k == 'bf' else [4, 43]}
    if spawns.get(a): e['spawns'] = spawns[a]
    if enemies.get(a): e['enemies'] = enemies[a]
    sol = g.solid_for_top_exits(a)
    if sol and k == 'bf': e['solid'] = sol
    ents.append(e)
G.write(ents, {41, 42, 43, 44}, world=W16)
p = os.path.join(G.HERE, 'areas.json'); cfg = json.load(open(p))
for v in cfg['new_areas']:
    if (v['world'], v['area']) == (16, 1):          # the crossroads ambush moves to the warehouse
        v['doors'] = [d for d in v['doors'] if d.get('event') != 'ch6_ambush' and not d.get('_gen6')] + \
                     [dict(d, _gen6=1) for d in g.doors[1]]
json.dump(cfg, open(p, 'w'), indent=1)
for a in SRC: print(a, NAMES[a], [(d.get('warp'), d['rect']) for d in g.doors[a] if 'warp' in d])
