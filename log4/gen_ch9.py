"""Chapter 9 'Years of Terror' (Act 3, Age 768, world 17): the way to Gero's bunker is the chapter 4 mountains again.
After Bulma the twins land in 17:37 Mountain Pass (the 1:108 map); the computer has sealed the bunker for an
"evaluation": its door (pass, west) opens once the Sentinel in 17:38 Generator Cave (the 1:109 map; enemy row 100,
BF Shadow Colossus) is destroyed. 17:39 Old Mine (the 1:110 map, BF 1:16) is optional (heavies, a cache). The bunker
17:12 gets the south corridor back to the pass. Flags 400 pass arrival, 401 Sentinel destroyed, 402 mine cache
(BF uses flags up to 387; the flag array runs to 895).
usage: python3 log4/gen_ch9.py"""
import json, os
import areagen as G
from areagen import hexcond

W17 = 17
SRC = {37: ('l2', None), 38: ('l2', None), 39: ('bf', [1, 16])}
SIZE = {37: (368, 472), 38: (269, 230), 39: (202, 302)}
NAMES = {37: 'Mountain Pass (768)', 38: 'Generator Cave (768)', 39: 'Old Mine (768)'}
g = G.Gen(SRC, SIZE, world=W17)
W_ = W17
g._m[37] = G.OUT.walk_mask(G.OUT.map_of(1, 108)); g._m[38] = G.OUT.walk_mask(G.OUT.map_of(1, 109))
g.link(37, ('right', 184, 296), 38, ('down', 72, 112), NAMES)
# Old Mine entrance: the hole at the top of the generator cave's east ramp (was a trail up the mountain pass's cliff
# behind a tree - invisible; user 2026-11-02: no hidden exits). The mine's barred gate says why it goes no deeper.
hole_arr = g.snap(38, 236, 128, 14, 'down')
g.doors[38].append({'rect': [228, 72, 269, 112], 'warp': [W_, 39] + g.arrival(39, 'down', 104, 136), 'dir': 'up',
                      'face': 'up', '_note': 'Generator Cave hole -> Old Mine'})
g.doors[39].append({'rect': g.rect(39, 'down', 104, 136), 'warp': [W_, 38] + hole_arr, 'dir': 'down', 'face': 'down',
                      '_note': 'Old Mine mouth -> Generator Cave'})
g.ev(39, (76, 96, 172, 176), 'mine_gate', examine='up', note='the barred shaft gate (no way down)')
pass_arr = g.arrival(37, 'left', 248, 360)
west = g.rect(37, 'left', 248, 360)
g.doors[37].append({'rect': west, 'warp': [W17, 12, 216, 280], 'dir': 'left', 'face': 'up',
                    'when': hexcond(('set', 401)), '_note': 'pass -> bunker, once the Sentinel is down (401)'})
g.ev(37, west, 'ch9_sealed', when=hexcond(('clear', 401)), examine='left', note='the sealed bunker door (401 clear)')
g.ev(37, (pass_arr[0] - 8, pass_arr[1] - 30, pass_arr[0] + 40, pass_arr[1] + 30), 'ch9_pass', walk=True,
     when=hexcond(('clear', 400)), note='landing in the mountains (400)')
g.ev(39, (24, 150, 56, 176), 'ch9_cache_mine', examine='left', note='the old mining cart (402)')
BUNKER_EVENT = {'rect': [192, 232, 248, 296], 'event': 'ch9_bunker', 'fn2': '0x080077DF', 'when': hexcond(('clear', 362)),
                '_note': 'the computer greets them at the south corridor too (the list checks 362)'}
BUNKER_DOOR = {'rect': [200, 300, 232, 336], 'warp': [W17, 37] + pass_arr, 'dir': 'down', 'face': 'right',
               '_note': 'bunker south corridor -> Mountain Pass (chapter 9)'}
S = lambda a, x, y, r=12, f=None: g.snap(a, x, y, r, f)
E = lambda a, t, x, y, **k: dict(type=t, x=S(a, x, y, 14)[0], y=S(a, x, y, 14)[1], **k)
PROTO, HEAVY, SENTINEL = 48, 62, 100
enemies = {
    37: [E(37, PROTO, 120, 270), E(37, HEAVY, 220, 260), E(37, PROTO, 300, 230), E(37, PROTO, 60, 320)],
    38: [E(38, PROTO, 150, 190), dict(E(38, SENTINEL, 200, 160), character=240, condition=0x20000 + 401,
                                      _note='the Sentinel (row 100, BF Shadow Colossus): until destroyed (401)')],
    39: [E(39, HEAVY, 60, 230), E(39, HEAVY, 150, 120), E(39, PROTO, 120, 250)],
}
ents = []
for a in (37, 38, 39):
    k, s = SRC[a]
    e = {'world': W17, 'area': a, 'template': [15, 10], 'name': 573, 'palette_act': 'act3',
         '_note': 'Chapter 9: %s (generated by log4/gen_ch9.py)' % NAMES[a], 'doors': g.doors[a],
         'map_from': s if k == 'bf' else [1, {37: 108, 38: 109}[a]], 'enemies': enemies[a]}
    sol = g.solid_for_top_exits(a)
    if sol and k == 'bf': e['solid'] = sol
    ents.append(e)
G.write(ents, {37, 38, 39}, world=W17)
p = os.path.join(G.HERE, 'areas.json'); cfg = json.load(open(p))
for v in cfg['new_areas']:
    if (v['world'], v['area']) == (17, 12):
        v['doors'] = [d for d in v['doors'] if d['rect'] not in (BUNKER_DOOR['rect'], BUNKER_EVENT['rect'])] + \
                     [BUNKER_DOOR, BUNKER_EVENT]
json.dump(cfg, open(p, 'w'), indent=1)
for a in SRC: print(a, NAMES[a], [(d.get('warp'), d['rect']) for d in g.doors[a] if 'warp' in d])
print('pass arrival', pass_arr)
