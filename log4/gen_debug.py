# chapter is reached by playing on. Flags: 430 = all moves; 431-436 = level 55/60/70/80/90/99 (one at a time).
# Skills: L cycles the selected skill, B uses it (BF's own selector); natives 164/165 add/remove (164 appends blindly,
# so every add is "remove, then add"). Levels: native 194 (0xC2) = Player_AddExp on the current character (BF's own
# level-up: stats regrown, level-up page); native 200 (0xC8) pushes the current character's level. gExpTable 0x6B7084.
import struct, sys
sys.path.insert(0, os.path.join(G.HERE, '..', 'tools')); import scenes
_bf = open(os.path.join(G.HERE, '..', 'bf.gba'), 'rb').read()
EXP = struct.unpack_from('<151I', _bf, 0x6B7084)                 # EXP needed for level 50 + i
MOVES_FLAG, LEVEL_FLAGS = 430, {431: 55, 432: 60, 433: 70, 434: 80, 435: 90, 436: 99}
MOVES = {0: [7, 6, 14], 2: [7, 8, 16], 1: [8, 7, 6, 17, 18, 20], 3: [8, 7, 6, 4, 11, 18], 6: [7, 15, 14, 1, 9]}
MOVES_ALSO = [440, 441]    # all moves also unlocks every outfit and Super 17 (skill 20 for character 1)

def level_code(T):
    """Bytecode: if the current character is level L (< T), add the EXP from L to T. One branch per level."""
    b = b''
    for L in range(50, T):
        d = EXP[T - 50] - EXP[L - 50]
        body = b'\x01' + scenes.enc_varint(d) + bytes([0x02, 0xC2, 0x11])
        b += bytes([0x02, 0xC8, 0x00, L, 0x0B, 0x13]) + struct.pack('>h', 2 + len(body)) + body
    return 'code ' + (b + b'\x11').hex(' ')

def apply_lines(tag, player, party, extra):
    """party: characters in the party when the list ends (player first); extra: ones to level that aren't."""
    L = ['unless_flag %d %s_nomoves' % (MOVES_FLAG, tag)]
    L += ['do ' + '; '.join('call 165 %d %d; call 164 %d %d' % (c, k, c, k) for k in MOVES[c]) for c in party + extra]
    L += ['set_flag %d' % f for f in MOVES_ALSO]
    L += ['label %s_nomoves' % tag]
    for f, T in LEVEL_FLAGS.items():
        L += ['unless_flag %d %s_l%d' % (f, tag, T)]
        for c in party + extra:
            if c == 6: continue
            pre = 'call 149 %d' % c if c in party else 'call 151 %d; call 149 %d' % (c, c)
            post = 'call 149 %d' % player if c in party else 'call 149 %d; call 152 %d' % (player, c)
            L += ['do ' + pre, level_code(T), 'do ' + post] if c != player else [level_code(T)]
        L += ['do heal', 'label %s_l%d' % (tag, T)]
    return L + ['label %s_done' % tag, 'do call 47; call 51 0']

