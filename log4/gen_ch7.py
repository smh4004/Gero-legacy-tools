"""Chapter 7 'Activation' (Act 3, Age 767): with Gero dead, his lab's security treats the twins as intruders. Pod room
1:81 south passage -> 1:111 Security Wing (BF Dr. Brief's Lab 4:31 map: failed prototypes, laser turrets) -> 1:112
Control Room (BF Computer Room 4:22 map: the Security Unit, enemy row 20 BF Destroyer; the console lifts the lockdown and
sends the twins out to the cave 1:82). Flags 338 alarm, 339 Security Unit destroyed, 329 locker.
usage: python3 log4/gen_ch7.py"""
import json, os
import areagen as G
from areagen import hexcond

SRC = {111: ('bf', [4, 31]), 112: ('bf', [4, 22]), 81: ('l2', '0x54261c')}
SIZE = {111: (448, 432), 112: (224, 192), 81: (322, 350)}
NAMES = {111: 'Security Wing', 112: 'Control Room', 81: 'Pod room'}
g = G.Gen(SRC, SIZE)
g.link(111, ('right', 96, 120), 112, ('right', 96, 112), NAMES)
for d in g.doors[111]: d['cover_ok'] = True     # BF's lab doors are panels in the wall: walking in, the wall covers
S = lambda a, x, y, r=12, f=None: g.snap(a, x, y, r, f)
wing_arr = g.arrival(111, 'left', 336, 352)
POD_DOOR = {'rect': [256, 296, 312, 326], 'warp': [1, 111] + wing_arr, 'dir': 'down', 'face': 'right',
            '_note': 'pod room south passage -> Security Wing (chapter 7)'}
g.doors[111].append({'rect': g.rect(111, 'left', 336, 352), 'warp': [1, 81] + S(81, 264, 264, 14, 'up'), 'dir': 'left', 'face': 'up',
                     'cover_ok': True, '_note': 'Security Wing -> pod room'})
g.ev(111, (wing_arr[0] - 8, wing_arr[1] - 32, wing_arr[0] + 48, wing_arr[1] + 32), 'ch7_alarm', walk=True,
     when=hexcond(('clear', 338)), note='the lockdown alarm (338)')
g.ev(111, (64, 96, 96, 120), 'ch7_locker', examine='up', note="Gero's workbench (329)")
g.ev(112, (96, 112, 140, 132), 'ch7_console', examine='up', note='the security console (needs 339)')

E = lambda a, t, x, y, **k: dict(type=t, x=S(a, x, y, 14)[0], y=S(a, x, y, 14)[1], **k)
PROTO, TURRET, UNIT = 48, 64, 20
enemies = {
    111: [E(111, PROTO, 120, 180), E(111, PROTO, 300, 200), E(111, PROTO, 200, 330), E(111, TURRET, 380, 110),
          E(111, TURRET, 380, 400)],
    112: [dict(E(112, UNIT, 120, 160), character=78, condition=0x20000 + 339,
               _note='Security Unit (row 20, BF Destroyer): until destroyed (339)')],
}
ents = []
for a in (111, 112):
    e = {'world': 1, 'area': a, 'map_from': SRC[a][1], 'template': [15, 10], 'name': 531, 'palette_act': 'act1',
         '_note': 'Chapter 7: %s (generated by log4/gen_ch7.py)' % NAMES[a], 'doors': g.doors[a], 'enemies': enemies[a]}
    ents.append(e)
G.write(ents, {111, 112})
p = os.path.join(G.HERE, 'areas.json'); cfg = json.load(open(p))
for v in cfg['new_areas']:
    if (v['world'], v['area']) == (1, 81):
        for d in v['doors']:
            if d['rect'] == POD_DOOR['rect']: d['warp'] = POD_DOOR['warp']; d['_note'] = POD_DOOR['_note']
json.dump(cfg, open(p, 'w'), indent=1)
for a in (111, 112): print(a, NAMES[a], [(d.get('warp'), d['rect']) for d in g.doors[a] if 'warp' in d])
print('wing arrival', wing_arr)
