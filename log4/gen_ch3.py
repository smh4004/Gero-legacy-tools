"""Chapter 3 'The Boy Called Goku': Red Ribbon HQ under attack. Gero takes the blueprint core (tank room pod), then
wipes the army's archive: lab south corridor -> munitions lines A/B/C (BF airship factory 12:5/12:9/12:15) -> the vault
(12:12, keycard from the looters' captain) -> the archive (4:22), whose console arms the self-destruct and sends Gero
out to the Northern Wastelands (1:71). Flags 283 factory arrival, 284 captain defeated (keycard), 285 archive wiped,
286/288 caches, 287 vault arrival. usage: python3 log4/gen_ch3.py"""
import json, os
import areagen as G
from areagen import hexcond

SRC = {103: ('bf', [12, 5]), 104: ('bf', [12, 9]), 105: ('bf', [12, 15]), 106: ('bf', [12, 12]), 107: ('bf', [4, 22])}
SIZE = {103: (496, 160), 104: (496, 160), 105: (496, 160), 106: (232, 168), 107: (248, 224)}
NAMES = {103: 'Munitions Line A', 104: 'Munitions Line B', 105: 'Munitions Line C', 106: 'Archive Vault', 107: 'Army Archive'}
g = G.Gen(SRC, SIZE)
g.link(103, ('right', 104, 136), 104, ('left', 104, 136), NAMES)
g.link(104, ('right', 104, 136), 105, ('left', 104, 136), NAMES)
g.link(105, ('down', 24, 56), 106, ('down', 192, 216), NAMES)
for d in g.doors[105]:                                     # small map: arrive just inside the vault's south door
    if d['warp'][1] == 106: d['warp'][2:] = [196, 128]
# the vault door (top centre of 12:12) -> the archive, once the keycard is taken (284); the archive's south door back
arch_arr = g.snap(107, 168, 100, 14, 'left')            # just inside the panel door
vault_arr = g.snap(106, 112, 120, 14, 'down')
g.doors[106].append({'rect': [104, 92, 136, 112], 'warp': [1, 107] + arch_arr, 'dir': 'up', 'face': 'up',
                     'when': hexcond(('set', 284)), '_note': 'vault door -> archive (keycard: flag 284)'})
g.doors[107].append({'rect': [196, 96, 224, 112], 'warp': [1, 106] + vault_arr, 'dir': 'right', 'face': 'down',
                     'cover_ok': True, '_note': 'archive panel door (east wall, as 1:112) -> vault. Was the bottom wall: '
                     'no visible door (user 2026-11-02: no hidden exits)'})
# lab 1:69's south corridor -> Line A once the core is taken (316)
a_arr = g.arrival(103, 'left', 104, 136)
LAB_DOOR = {'rect': [200, 300, 232, 336], 'warp': [1, 103] + a_arr, 'dir': 'down', 'face': 'right',
            'when': hexcond(('set', 316)), '_note': 'lab south corridor -> Munitions Line A (after the core, 316)'}
back = {'rect': g.rect(103, 'left', 104, 136), 'warp': [1, 69, 216, 280], 'dir': 'left', 'face': 'up', '_note': 'Line A -> lab'}
g.doors[103].append(back)

g.ev(103, (a_arr[0] - 8, 96, a_arr[0] + 40, 140), 'ch3_factory', walk=True, when=hexcond(('clear', 283)), note='first arrival (283)')
g.ev(106, (vault_arr[0] - 30, vault_arr[1] - 20, vault_arr[0] + 30, vault_arr[1] + 30), 'ch3_vault', walk=True,
     when=hexcond(('clear', 287)), note='vault first arrival (287)')
g.ev(106, (104, 92, 136, 116), 'vault_locked', examine='up', when=hexcond(('clear', 284)), note='locked vault door')
g.ev(107, (96, 112, 140, 132), 'ch3_archive', examine='up', note='the archive console')
g.ev(105, (370, 96, 400, 140), 'cache_line', examine='right', note='a crate of field rations at the end of Line C (288)')
g.ev(104, (190, 96, 230, 108), 'cache_belt', examine='up', note='a parts bin by the press (286)')

E = lambda a, t, x, y, **k: dict(type=t, x=g.snap(a, x, y, 10)[0], y=g.snap(a, x, y, 10)[1], **k)
GUN, CRIM, TUR, MERC, CAPT = 44, 15, 64, 75, 47
enemies = {
    103: [E(103, CRIM, 180, 112), E(103, GUN, 300, 112)],
    104: [E(104, CRIM, 120, 112), E(104, MERC, 240, 112), E(104, CRIM, 340, 112)],
    105: [E(105, GUN, 160, 112), dict(E(105, CAPT, 280, 112), character=141, condition=0x20000 + 284,
                                      _note="looters' captain (row 47 Hooligan): drops the vault keycard (284)")],
    106: [],
    107: [E(107, GUN, 180, 160)],
}
ents = []
for a in SRC:
    k, s = SRC[a]
    e = {'world': 1, 'area': a, 'map_from': s, 'template': [1, 1], 'name': 1700, 'palette_act': 'act1',
         '_note': 'Chapter 3: %s (generated by log4/gen_ch3.py)' % NAMES[a], 'doors': g.doors[a]}
    if enemies.get(a): e['enemies'] = enemies[a]
    if a in (103, 104, 105): e['clipcheck_periodic'] = True   # identical presses repeat every ~140 px
    ents.append(e)
G.write(ents, set(SRC))
# lab 1:69: the south corridor
p = os.path.join(G.HERE, 'areas.json'); cfg = json.load(open(p))
for v in cfg['new_areas']:
    if (v['world'], v['area']) == (1, 69):
        v['doors'] = [d for d in v['doors'] if d.get('event') != 'lift_talk' and not ('warp' in d and d['warp'][1] == 103)]
        v['doors'].append(LAB_DOOR)
        v['doors'].append({'rect': [200, 296, 232, 336], 'examine': 'down', 'event': 'ch3_corridor', 'when': hexcond(('clear', 316)),
                           '_note': 'south corridor before the core is taken'})
    if (v['world'], v['area']) == (1, 70):       # the escape now starts from the archive
        v['doors'] = [d for d in v['doors'] if not ('warp' in d and d['warp'][1] == 71)]
json.dump(cfg, open(p, 'w'), indent=1)
for a in SRC: print(a, NAMES[a], [(d.get('warp'), d['rect']) for d in g.doors[a] if 'warp' in d])
