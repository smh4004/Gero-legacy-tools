"""Chapter 4 'The First Androids': the bunker years. Relay 1 is in the bunker; relays 2 and 3 are outside: bunker south
corridor -> 1:108 Mountain Pass (LoG2 8:40, waterfall and bridge) -> 1:109 Generator Cave (LoG2 8:36, relay 2) and
1:110 Old Mine (BF Cave of the Ancients 1:16, relay 3 behind Prototype 9). Relay nodes are visible NPCs. Flags 289
pass arrival, 290 Prototype 9 destroyed, 291/292 caches. usage: python3 log4/gen_ch4.py"""
import json, os
import areagen as G
from areagen import hexcond

SRC = {108: ('l2', '0x559d90'), 109: ('l2', '0x55f728'), 110: ('bf', [1, 16])}
SIZE = {108: (368, 472), 109: (269, 230), 110: (202, 302)}
NAMES = {108: 'Mountain Pass', 109: 'Generator Cave', 110: 'Old Mine'}
g = G.Gen(SRC, SIZE)
W_ = 1
g.link(108, ('right', 184, 296), 109, ('down', 72, 112), NAMES)
# Old Mine entrance: the hole at the top of the generator cave's east ramp (was a trail up the mountain pass's cliff
# behind a tree - invisible; user 2026-11-02: no hidden exits). The mine's barred gate says why it goes no deeper.
hole_arr = g.snap(109, 236, 128, 14, 'down')
g.doors[109].append({'rect': [228, 72, 269, 112], 'warp': [W_, 110] + g.arrival(110, 'down', 104, 136), 'dir': 'up',
                      'face': 'up', '_note': 'Generator Cave hole -> Old Mine'})
g.doors[110].append({'rect': g.rect(110, 'down', 104, 136), 'warp': [W_, 109] + hole_arr, 'dir': 'down', 'face': 'down',
                      '_note': 'Old Mine mouth -> Generator Cave'})
g.ev(110, (76, 96, 172, 176), 'mine_gate', examine='up', note='the barred shaft gate (no way down)')
pass_arr = g.arrival(108, 'left', 248, 360)
LAB_DOOR = {'rect': [200, 300, 232, 336], 'warp': [1, 108] + pass_arr, 'dir': 'down', 'face': 'right',
            '_note': 'bunker south corridor -> Mountain Pass'}
g.doors[108].append({'rect': g.rect(108, 'left', 248, 360), 'warp': [1, 72, 216, 280], 'dir': 'left', 'face': 'up',
                     '_note': 'Mountain Pass -> bunker'})
g.ev(108, (pass_arr[0] - 8, pass_arr[1] - 30, pass_arr[0] + 40, pass_arr[1] + 30), 'ch4_pass', walk=True,
     when=hexcond(('clear', 289)), note='first arrival (289)')
g.ev(109, (40, 196, 72, 224), 'cache_gen', examine='left', note='an old Red Ribbon locker (291)')
g.ev(110, (24, 150, 56, 176), 'cache_mine', examine='left', note='a mining cart (292)')
S = lambda a, x, y, r=12: g.snap(a, x, y, r)
spawns = {109: [dict(zip(('x', 'y'), S(109, 176, 150)), actor='drone_l2', face='down', talk='relay_2', _note='relay node 2')],
          110: [dict(zip(('x', 'y'), S(110, 112, 150)), actor='drone_l2', face='down', talk='relay_3', _note='relay node 3')]}
E = lambda a, t, x, y, **k: dict(type=t, x=S(a, x, y, 14)[0], y=S(a, x, y, 14)[1], **k)
CRIM, GUN, PROTO, P9 = 15, 44, 48, 41
enemies = {
    108: [E(108, CRIM, 120, 270), E(108, GUN, 220, 260), E(108, PROTO, 300, 230), E(108, CRIM, 60, 320)],
    109: [E(109, PROTO, 150, 190), E(109, PROTO, 240, 200)],
    110: [E(110, PROTO, 60, 230), dict(E(110, P9, 160, 176), character=133, condition=0x20000 + 290,
                                       _note='Prototype 9 (row 41, BF Grand Mechanoid): until destroyed (290)')],
}
ents = []
for a in SRC:
    k, s = SRC[a]
    e = {'world': 1, 'area': a, 'template': [15, 10], 'name': 573, 'palette_act': 'act1',
         '_note': 'Chapter 4: %s (generated by log4/gen_ch4.py)' % NAMES[a], 'doors': g.doors[a]}
    if k == 'bf': e['map_from'] = s
    else: e['map_log2'] = s
    if spawns.get(a): e['spawns'] = spawns[a]
    if enemies.get(a): e['enemies'] = enemies[a]
    sol = g.solid_for_top_exits(a)
    if sol and k == 'bf': e['solid'] = sol
    ents.append(e)
G.write(ents, set(SRC))
p = os.path.join(G.HERE, 'areas.json'); cfg = json.load(open(p))
for v in cfg['new_areas']:
    if (v['world'], v['area']) == (1, 72):
        v['doors'] = [d for d in v['doors'] if not ('warp' in d and d['warp'][1] == 108)] + [LAB_DOOR]
    if (v['world'], v['area']) in ((1, 74), (1, 76)):
        v['doors'] = [d for d in v['doors'] if d.get('event') not in ('relay_2', 'relay_3')]
json.dump(cfg, open(p, 'w'), indent=1)
for a in SRC: print(a, NAMES[a], [(d.get('warp'), d['rect']) for d in g.doors[a] if 'warp' in d], spawns.get(a))
