"""Chapter 10 'The Last Stand' (Act 3, Age 780, world 17): the twins come into West City from the west, through the
ruined Circus Lot (17:40, BF Musuka Circus 3:14 map), where the resistance has left Capsule Corporation's war machines
and turrets to slow them down; the ruins' west road (17:21) leads to the crossroads and Gohan (ch10_rain).
Flags 403 circus-lot cache. usage: python3 log4/gen_ch10.py"""
import json, os
import areagen as G

W17 = 17
SRC = {21: ('bf', [4, 1]), 40: ('bf', [3, 14])}
SIZE = {21: (1072, 912), 40: (480, 240)}
NAMES = {21: 'West City ruins (780)', 40: 'Circus Lot ruins (780)'}
g = G.Gen(SRC, SIZE, world=W17)
arr = g.link(21, ('left', 312, 424), 40, ('right', 112, 184), NAMES)
S = lambda a, x, y, r=12, f=None: g.snap(a, x, y, r, f)
g.ev(40, (36, 24, 76, 70), 'ch10_cache', examine='up', note='a wrecked food stall (403)')
E = lambda a, t, x, y, **k: dict(type=t, x=S(a, x, y, 14)[0], y=S(a, x, y, 14)[1], **k)
HEAVY, TURRET, DRONE = 62, 64, 94
enemies = {40: [E(40, HEAVY, 120, 40), E(40, TURRET, 250, 140), E(40, DRONE, 330, 60), E(40, HEAVY, 420, 60),
                E(40, TURRET, 60, 60)]}
ents = [{'world': W17, 'area': 40, 'template': [15, 10], 'name': 1701, 'palette_act': 'act3', 'map_from': [3, 14],
         '_note': 'Chapter 10: %s (generated by log4/gen_ch10.py)' % NAMES[40], 'doors': g.doors[40],
         'enemies': enemies[40]}]
G.write(ents, {40}, world=W17)
p = os.path.join(G.HERE, 'areas.json'); cfg = json.load(open(p))
for v in cfg['new_areas']:
    if (v['world'], v['area']) == (17, 21):
        v['doors'] = [d for d in v['doors'] if not d.get('_gen10')] + [dict(d, _gen10=1) for d in g.doors[21]]
json.dump(cfg, open(p, 'w'), indent=1)
for a in SRC: print(a, NAMES[a], [(d.get('warp'), d['rect']) for d in g.doors[a] if 'warp' in d])
print('circus lot arrival from the east edge', arr[40])
