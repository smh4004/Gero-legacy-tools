def NPC(g, a, x, y, talk, note, face='down', **k):
    p = g.snap(a, x, y, 12)
    d = dict(x=p[0], y=p[1], face=face, talk=talk, _note=note); d.update(k)
    return d


def entry(world, area, name, pal, note, src, doors, spawns=None, enemies=None, **k):
    e = {'world': world, 'area': area, 'template': [15, 10], 'name': name, 'palette_act': pal,
         '_note': note + ' (generated by log4/gen_more.py)', 'doors': doors}
    kind, s = src
    if kind == 'bf': e['map_from'] = s
    elif kind == 'from': e['map_from'] = s
    else: e['map_log2'] = s
    if spawns: e['spawns'] = spawns
    if enemies: e['enemies'] = enemies
    e.update(k)
    NEW.append(e)


