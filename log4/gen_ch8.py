"""Chapter 8 'The Massacre' (Act 3, Age 767, world 17 = act3 palette): before the Z Fighters come, Eighteen wants to see
the twins' old hideout. 17:1 West City south road -> 17:34 Riverside (BF 2:9) -> 17:35 Docks (BF 2:8) -> barn door ->
17:36 Old Warehouse (the 4:43 map): the tin box (ch8_hideout, flag 359; the fruit stall's memory needs it). Gero's
hunter machines still patrol the docks, eight years after the twins were taken (rows 94 drone, 62 heavy).
Flags 359 hideout memory, 369 docks cache, 382 riverside cache. usage: python3 log4/gen_ch8.py"""
import json, os
import areagen as G

W17 = 17
SRC = {1: ('bf', [4, 1]), 34: ('bf', [2, 9]), 35: ('bf', [2, 8]), 36: ('l2', None)}
SIZE = {1: (1072, 912), 34: (480, 320), 35: (480, 480), 36: (368, 301)}
NAMES = {1: 'West City (767)', 34: 'Riverside (767)', 35: 'Docks (767)', 36: 'Old Warehouse (767)'}
UI_NAME = {34: 1702, 35: 1703, 36: 1704}
g = G.Gen(SRC, SIZE, world=W17)
g._m[36] = G.OUT.walk_mask(G.OUT.map_of(4, 43))
g.link(1, ('down', 368, 472), 34, ('up', 224, 288), NAMES)
g.link(34, ('right', 176, 272), 35, ('down', 232, 280), NAMES)   # the docks' pier (was the west edge behind the trees)
S = lambda a, x, y, r=12, f=None: g.snap(a, x, y, r, f)
g.doors[35].append({'rect': [120, 186, 168, 208], 'warp': [W17, 36] + S(36, 140, 104, 14, 'down'), 'dir': 'up',
                    'face': 'down', '_note': 'Docks -> Old Warehouse (barn door)'})
g.doors[36].append({'rect': [120, 64, 192, 92], 'warp': [W17, 35] + S(35, 136, 214, 14, 'down'), 'dir': 'up',
                    'face': 'down', 'cover_ok': True, '_note': 'Old Warehouse -> Docks'})
g.ev(36, (304, 224, 360, 252), 'ch8_hideout', examine='down', note='the loose board: the tin box (359)')
g.ev(34, (40, 120, 72, 152), 'ch8_cache_river', examine='left', note='the rowboat, rotted (382)')
g.ev(35, (256, 186, 288, 240), 'ch8_cache_docks', note='the dome house (369). Rect reaches y 240: the player stops at y 232 in front of the door (2026-11-04 playthrough: the old rect ended at 208, out of reach)')

E = lambda a, t, x, y, **k: dict(type=t, x=S(a, x, y, 14)[0], y=S(a, x, y, 14)[1], **k)
DRONE, HEAVY = 94, 62             # Power Mechandoid (char 230), Knight Destroyer (char 164)
enemies = {
    34: [E(34, DRONE, 200, 170), E(34, DRONE, 360, 220), E(34, HEAVY, 120, 230)],
    35: [E(35, DRONE, 100, 320), E(35, HEAVY, 320, 260), E(35, DRONE, 230, 110), E(35, DRONE, 380, 120)],
    36: [E(36, HEAVY, 220, 200), E(36, DRONE, 80, 180)],
}
ents = []
for a in (34, 35, 36):
    k, s = SRC[a]
    e = {'world': W17, 'area': a, 'template': [15, 10], 'name': UI_NAME[a], 'palette_act': 'act3',
         '_note': 'Chapter 8: %s (generated by log4/gen_ch8.py)' % NAMES[a], 'doors': g.doors[a],
         'map_from': s if k == 'bf' else [4, 43], 'enemies': enemies[a]}
    sol = g.solid_for_top_exits(a)
    if sol and k == 'bf': e['solid'] = sol
    ents.append(e)
G.write(ents, {34, 35, 36}, world=W17)
p = os.path.join(G.HERE, 'areas.json'); cfg = json.load(open(p))
for v in cfg['new_areas']:
    if (v['world'], v['area']) == (17, 1):
        v['doors'] = [d for d in v['doors'] if not d.get('_gen8')] + [dict(d, _gen8=1) for d in g.doors[1]]
json.dump(cfg, open(p, 'w'), indent=1)
for a in SRC: print(a, NAMES[a], [(d.get('warp'), d['rect']) for d in g.doors[a] if 'warp' in d])
