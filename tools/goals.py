"""Journal goals (Goals / Completed Goals screen).

BF's goal table (ROM 0x720564, 40 x 16 bytes, read by the journal builder at 0x080141EE, count = cmp r6,#0x28 at
0x08014254): [u8 category][u8][u16 UI string][ptr hide-if][ptr done-if][ptr active-if], each a bytecode condition.
A goal is listed under Completed when done-if is true, under Goals when active-if is true, and nowhere when hide-if is
true. The two RAM lists hold 40 entries each, so finished chapters' goals are hidden (hide-if = the next chapter has
started).
LoG4: log4/goals.json [{"text", "active", "done", "hide"}] -> UI strings 1600+ (text_tool ui_goals.txt) and a new
table. Conditions: "always", "never", or "set:N" / "clear:N" terms joined by "&"."""
import json, os, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import scenes
LIT, COUNT_AT, UI0 = 0x1441C, 0x14254, 1600


def cond(spec):
    if spec == 'always': return b'\x00\x01\x11'
    if spec == 'never': return b'\x00\x00\x11'
    out = b''
    for i, t in enumerate(spec.split('&')):
        k, f = t.strip().split(':')
        out += b'\x01' + scenes.enc_varint(int(f)) + bytes([0x02, 27 if k == 'set' else 28])
        if i: out += b'\x04'
    return out + b'\x11'


def write_ui(cfg_path, textdir):
    goals = json.load(open(cfg_path))['goals']
    with open(os.path.join(textdir, 'ui_goals.txt'), 'w') as f:
        f.write('# generated by tools/goals.py from log4/goals.json - edit that file instead\n\n')
        for i, g in enumerate(goals): f.write('[ui:%d]\n= %s\n\n' % (UI0 + i, g['text']))


def apply(rom, cfg_path, at):
    goals = json.load(open(cfg_path))['goals']
    assert len(goals) <= 100, 'goal texts are UI 1600-1699 (area names start at 1700)'
    assert rom[COUNT_AT:COUNT_AT + 2] == b'\x28\x2e', 'goal count instruction changed'
    cache, tab = {}, bytearray()
    def put(code):
        nonlocal at
        if code not in cache:
            rom[at:at + len(code)] = code; cache[code] = 0x08000000 + at; at += len(code)
        return cache[code]
    for i, g in enumerate(goals):
        tab += struct.pack('<BBHIII', 0, 0, UI0 + i, put(cond(g.get('hide', 'never'))), put(cond(g['done'])),
                           put(cond(g['active'])))
    at = (at + 3) & ~3
    rom[at:at + len(tab)] = tab
    struct.pack_into('<I', rom, LIT, 0x08000000 + at)
    rom[COUNT_AT] = len(goals)
    return at + len(tab)
