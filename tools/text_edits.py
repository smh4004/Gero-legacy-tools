"""LoG4's text as a delta against Buu's Fury's own (so the repo never carries the game's script).
  make : python3 tools/text_edits.py make  <clean bf.gba>   log4/text/*.txt -> log4/text_edits.json (changed + new only)
  apply: python3 tools/text_edits.py apply <clean bf.gba>   export BF's text, apply log4/text_edits.json -> log4/text/
log4/text/ui_goals.txt is generated by the build (tools/goals.py) and is not part of the delta."""
import json, os, sys, tempfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import text_tool

HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'log4')
FILES = ('ui.txt', 'dialogue.txt')


def entries(path):
    """[(key, header line, text line)] in file order, plus the file's leading comment block."""
    out, head, pre = [], None, []
    for line in open(path, encoding='utf-8'):
        line = line.rstrip('\n')
        if line.startswith('['): head = line
        elif (line.startswith('= ') or line == '=') and head is not None:
            out.append((head[1:head.index(']')], head, line)); head = None
        elif not out and head is None: pre.append(line)
    return out, pre


def make(clean):
    tmp = tempfile.mkdtemp(); text_tool.export(clean, tmp)
    delta = {}
    for f in FILES:
        base = {k: (h, t) for k, h, t in entries(os.path.join(tmp, f))[0]}
        cur, _ = entries(os.path.join(HERE, 'text', f))
        delta[f] = [[k, h, t] for k, h, t in cur if base.get(k) != (h, t)]
        gone = set(base) - {k for k, _, _ in cur}
        assert not gone, '%s: entries removed (%d) - not supported by the delta' % (f, len(gone))
    json.dump({'_note': 'LoG4 text edits vs Buu\'s Fury (USA): [key, header line, "= text"]; tools/text_edits.py',
               **delta}, open(os.path.join(HERE, 'text_edits.json'), 'w'), indent=0, ensure_ascii=False)
    print({f: len(v) for f, v in delta.items()})


def apply(clean):
    d = json.load(open(os.path.join(HERE, 'text_edits.json'), encoding='utf-8'))
    out = os.path.join(HERE, 'text'); text_tool.export(clean, out)
    for f in FILES:
        base, pre = entries(os.path.join(out, f))
        ed = {k: (h, t) for k, h, t in d[f]}
        lines = list(pre)
        for k, h, t in base:
            h, t = ed.pop(k, (h, t)); lines += [h, t, '']
        for k, h, t in d[f]:
            if k in ed: lines += [h, t, '']
        open(os.path.join(out, f), 'w', encoding='utf-8').write('\n'.join(lines).rstrip('\n') + '\n')
    print('log4/text rebuilt from the clean ROM + %s edits' % {f: len(d[f]) for f in FILES})


if __name__ == '__main__':
    {'make': make, 'apply': apply}[sys.argv[1]](sys.argv[2])
